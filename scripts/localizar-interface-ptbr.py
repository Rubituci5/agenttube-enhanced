def translate_node(m):
 t=m.group(1)
 v=t.strip()
 if v not in TEXT: return t
 return t[:len(t)-len(t.lstrip())]+TEXT[v]+t[len(t.rstrip()):]
s,n=re.subn(r'(?<=>)([^<>]+)(?=<)',translate_node,s)
# Only visible attributes.
def translate_attr(m):
 prefix,q,t=m.group(1),m.group(2),m.group(3)
 return prefix+q+ATTR.get(t,t)+q
s=re.sub(r'(\b(?:placeholder|aria-label|title)=)(["\'])(.*?)\2',translate_attr,s,flags=re.S)
